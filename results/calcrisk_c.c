#include <stddef.h>

static const int N_FEATURES = 8;

static const double MU[8] = {263.749, 0.154729, 12.6086, 280929, 2240.16, 75.2385, 10445.2, 7.97709};
static const double SIGMA[8] = {214.002, 0.214343, 11.7684, 436956, 450.715, 22.595, 11143.4, 2.39874};

static const double B[9] = {2.43088, 0.168025, 0.0054804, 0.039253, 0.00575199, -0.0138615, 0.0407215, 0.0665723, 0.0312424};

double calcrisk_c(const double *x, int n)
{
    if (x == NULL) return 0.0;
    if (n != N_FEATURES) return 0.0; /* caller must pass correct length */

    /* compute normalized features and linear model with intercept */
    double sum = B[0]; /* intercept */
    for (int i = 0; i < N_FEATURES; ++i) {
        double xi = x[i];
        double s = SIGMA[i];
        double norm = (s == 0.0) ? (xi - MU[i]) : ((xi - MU[i]) / s);
        sum += B[i+1] * norm;
    }
    return sum;
}
